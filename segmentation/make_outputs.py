matplotlib.use("Agg")

import matplotlib.patches as mpatches
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy import ndimage as ndi

from metadata.config import PROJECT_ROOT
from metadata.derived import (
    BRAIN_MASK,
    FLAIR_NORM,
    PRED_WMH,
    TISSUE_SEG,
    load_derived,
    load_derived_mask,
)
from metadata.geometry import voxel_spacing_mm, voxel_volume_mm3
from metadata.loader import load_nifti, load_split, load_wmh_mask, subjects_by_key
from metadata.provenance import get_git_commit_hash, write_manifest
from metadata.runlog import setup_logging
