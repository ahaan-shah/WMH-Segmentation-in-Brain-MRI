"""Build the Week 3 section of the `outputs/` gallery.

Same three rules as the Week 2 gallery (`preprocessing/make_outputs.py`): every
figure carries its own point of comparison, is named in plain words, and is
generated by committed code with the commit stamped on it. Each week's figure
code lives with that week's pipeline code; the gallery they write into is shared.

    code/.venv/bin/python -m segmentation.make_outputs
"""

