    axes = np.atleast_2d(axes)
    for row, s in enumerate(subjects):
        _panel(axes[row, 0], s.slice_of(s.raw), f"{s.label}\nBEFORE — original scan", vmax=s.raw_vmax)
        _reference_badge(axes[row, 0])
        _panel(axes[row, 1], s.slice_of(s.raw), "AFTER — head outlined in blue", vmax=s.raw_vmax)
        axes[row, 1].contour(s.slice_of(s.head).T[::-1], colors="deepskyblue", linewidths=1.1)
        sagittal = s.head[s.head.shape[0] // 2]
        raw_sag = s.raw[s.raw.shape[0] // 2]
