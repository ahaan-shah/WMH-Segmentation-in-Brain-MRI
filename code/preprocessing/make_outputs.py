def _stamp(fig, title: str, subtitle: str, commit: str) -> None:
    """Title + subtitle, spaced by figure height.

    Fixed y-positions collide on short (single-row) figures — the subtitle runs
    straight through the title. Converting a fixed point offset into figure
    fraction keeps the gap constant whatever the figure height.
    """
    height_inches = fig.get_size_inches()[1]
    title_y = 1.0 - (0.18 / height_inches)
    subtitle_y = 1.0 - (0.48 / height_inches)
    fig.suptitle(title, fontsize=14, fontweight="bold", y=title_y)
    fig.text(0.5, subtitle_y, subtitle, ha="center", fontsize=9.5, style="italic", wrap=True)
    fig.text(0.995, 0.004, f"commit {commit[:8]}", ha="right", fontsize=6.5, color="grey")


def _save(fig, path, commit: str, logger) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=130, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    write_manifest(path, generating_script=f"code/preprocessing/{SCRIPT_NAME}.py",
                   extra={"commit": commit})
    logger.info("  %s", path.relative_to(PROJECT_ROOT))


def _panel(axis, image, title, *, vmin=0, vmax=None, cmap="gray"):
    axis.imshow(image.T[::-1], cmap=cmap, vmin=vmin, vmax=vmax)
    axis.set_title(title, fontsize=9)
    axis.axis("off")


def _reference_badge(axis) -> None:
    """Mark which panel is the thing everything else is compared against."""
    axis.set_title(axis.get_title(), fontsize=9, color="#B22222", fontweight="bold")


class Subject:
    """Everything one representative subject contributes to the gallery."""

    def __init__(self, key: str):
        subjects = subjects_by_key()
        self.meta = subjects[key]
        self.key = key
        self.site = self.meta.site
        self.label = f"{self.meta.site} {self.meta.subject_id}"
        image = load_nifti(self.meta.flair_path)
        self.spacing = voxel_spacing_mm(image)
        self.voxel_volume = voxel_volume_mm3(image)
        self.raw = np.asarray(image.dataobj, dtype=float)
        self.t1 = np.asarray(load_nifti(self.meta.t1_path).dataobj, dtype=float)
        self.head = load_derived_mask(key, HEAD_MASK)
        self.brain = load_derived_mask(key, BRAIN_MASK)
        self.bias = np.asarray(load_derived(key, BIAS_FIELD).dataobj, dtype=float)
        self.n4 = np.asarray(load_derived(key, FLAIR_N4).dataobj, dtype=float)
        self.norm = np.asarray(load_derived(key, FLAIR_NORM).dataobj, dtype=float)
        self.tissue = np.asarray(load_derived(key, TISSUE_SEG).dataobj)
        self.lesion = load_wmh_mask(self.meta.mask_path)
        self.z = int(np.argmax(self.lesion.sum(axis=(0, 1))))
        self.raw_vmax = float(np.percentile(self.raw[self.head], 99.5))
        self.brain_vmax = float(np.percentile(self.n4[self.brain], 99.5))

    def slice_of(self, volume):
        return volume[:, :, self.z]


def pick_subjects(logger) -> list[Subject]:
    """Median lesion-burden subject per site — typical, not cherry-picked."""
    subjects = subjects_by_key()
    rows = []
    for key in load_split("train"):
        rows.append({"key": key, "site": subjects[key].site,
                     "vox": int(load_wmh_mask(subjects[key].mask_path).sum())})
    table = pd.DataFrame(rows)
    chosen = []
    for site in SITES:
        group = table[table.site == site].sort_values("vox").reset_index(drop=True)
        chosen.append(group.loc[len(group) // 2, "key"])
    logger.info("representative subjects (median lesion burden per site): %s", chosen)
    return [Subject(k) for k in chosen]


