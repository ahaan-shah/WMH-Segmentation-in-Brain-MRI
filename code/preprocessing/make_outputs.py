def figure_denoising_rejected(subject, commit, logger) -> None:
    """Zoom where the SMALL lesions are, and mark which ones each filter destroys.

    An earlier version cropped around the largest lesion in the slice. Large
    lesions survive every filter, so the figure argued the opposite of the
    finding. It now centres on the slice richest in small lesions and colours
    each lesion by whether it survived, which is the actual claim.
    """
    small_threshold = 10
    labelled, n = ndi.label(subject.lesion, structure=np.ones((3, 3, 3)))
    sizes = np.bincount(labelled.ravel())[1:]
    small_ids = {i + 1 for i in range(n) if sizes[i] <= small_threshold}
    if not small_ids:
        small_ids = {int(np.argmin(sizes)) + 1}

    small_mask = np.isin(labelled, list(small_ids))
    z = int(np.argmax(small_mask.sum(axis=(0, 1))))
    coords = np.argwhere(small_mask[:, :, z])
    cx, cy = coords.mean(axis=0).astype(int)
    half = 38
    x0, x1 = max(0, cx - half), min(subject.norm.shape[0], cx + half)
    y0, y1 = max(0, cy - half), min(subject.norm.shape[1], cy + half)

    variants = [("BEFORE — no filtering", subject.norm)]
    for name, method in (("anisotropic diffusion", "curvature_anisotropic_diffusion"),
                         ("Gaussian blur", "gaussian")):
        filtered = denoise(subject.norm, subject.spacing, method=method)
        variants.append((name, np.where(subject.brain, filtered, 0.0)))
    variants.append(("CLAHE contrast boost", clahe(subject.norm, subject.brain)))

    visible = [i for i in small_ids if (labelled[:, :, z] == i).any()]
    fig, axes = plt.subplots(1, len(variants), figsize=(4.1 * len(variants), 5.4))

    for column, (name, volume) in enumerate(variants):
        axes[column].imshow(volume[x0:x1, y0:y1, z].T[::-1], cmap="gray", vmin=0, vmax=2.0)
        destroyed = 0
        for lesion_id in visible:
            component = labelled == lesion_id
            before = float(subject.norm[component].mean()) - 1.0
            after = float(volume[component].mean()) - 1.0
            survived = before <= 0 or (after / before) >= 0.5
            destroyed += 0 if survived else 1
            outline = (component[x0:x1, y0:y1, z]).T[::-1]
            axes[column].contour(outline, colors=LESION_GREEN if survived else "red",
                                 linewidths=1.4)
        if column == 0:
            caption = "all lesions intact"
        elif name.startswith("CLAHE"):
            # CLAHE loses no lesions, but that is not a pass — it amplifies
            # everything including noise (-57% contrast-to-noise measured) and
            # destroys the 1.0 = white matter scale. Without this the panel
            # reads as though CLAHE were the good option.
            caption = "0 lesions lost, but look at the noise:\ncontrast-to-noise fell 57%"
        else:
            caption = (f"{destroyed} of {len(visible)} small lesions\n"
                       "lost over half their visibility")
        axes[column].set_title(f"{name}\n{caption}", fontsize=9.5,
                               color="#B22222" if column == 0 else "black",
                               fontweight="bold" if column == 0 else "normal")
        axes[column].axis("off")

    _stamp(fig, "STEP 6 — image smoothing: TESTED AND REJECTED",
           f"Close-up on the small lesions of {subject.label}. GREEN = lesion survived, "
           "RED = lost over half its visibility. Half the lesions in this dataset are 5 voxels "
           "or smaller, which is exactly what smoothing erases.", commit)
    fig.tight_layout(rect=(0, 0, 1, 0.88))
    _save(fig, WEEK2 / "06-smoothing-REJECTED" / "why-smoothing-was-rejected.png", commit, logger)


def figure_morphology_cost(subject, commit, logger) -> None:
    thresholds = (3, 5, 10)
    fig, axes = plt.subplots(1, len(thresholds) + 2, figsize=(4.0 * (len(thresholds) + 2), 4.6))

    stripped = np.where(subject.brain, subject.norm, 0.0)
    axes[0].imshow(subject.slice_of(stripped).T[::-1], cmap="gray", vmin=0, vmax=2.0)
    axes[0].contour(subject.slice_of(subject.lesion).T[::-1], colors=LESION_GREEN, linewidths=1.0)
    axes[0].set_title("BEFORE — all true lesions", fontsize=10, color="#B22222", fontweight="bold")
    axes[0].axis("off")

    for column, threshold in enumerate(thresholds, start=1):
        kept, info = remove_small_components(subject.lesion, threshold)
        lost = subject.lesion & ~kept
        axes[column].imshow(subject.slice_of(stripped).T[::-1], cmap="gray", vmin=0, vmax=2.0)
        axes[column].contour(subject.slice_of(kept).T[::-1], colors=LESION_GREEN, linewidths=1.0)
        if lost.any():
            axes[column].contour(subject.slice_of(lost).T[::-1], colors="red", linewidths=1.2)
        axes[column].set_title(f"delete blobs under {threshold} voxels\n"
                               f"{info['components_removed']} of {info['components_before']} "
                               f"lesions deleted (red)", fontsize=9)
        axes[column].axis("off")

    rows = minimum_size_cost(subject.lesion, subject.voxel_volume, (2, 3, 5, 10, 20))
    table = pd.DataFrame(rows)
    axis = axes[-1]
    axis.plot(table.minimum_voxels, 100 * table.lesion_count_fraction_removed,
              "o-", color="#B22222", label="% of LESIONS lost")
    axis.plot(table.minimum_voxels, 100 * table.volume_fraction_removed,
              "s-", color="#4C72B0", label="% of VOLUME lost")
    axis.set(xlabel="delete blobs smaller than (voxels)", ylabel="percent lost",
             title="the trap, as a graph")
    axis.legend(fontsize=8)
    axis.grid(alpha=0.3)

    _stamp(fig, "STEP 7 — the clean-up tool Week 3 will use, and what it costs",
           "Deleting small blobs removes false alarms but also real lesions. The graph is the point: "
           "the red line (lesions lost) shoots up while the blue line (volume lost) barely moves — "
           "so a volume-based score would call this harmless when it is not.", commit)
    fig.tight_layout(rect=(0, 0, 1, 0.90))
    _save(fig, WEEK2 / "07-cleanup-tools" / "cost-of-deleting-small-blobs.png", commit, logger)


