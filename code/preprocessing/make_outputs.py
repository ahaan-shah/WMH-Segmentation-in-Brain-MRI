"""Build the human-browsable `outputs/` gallery.

This is the presentation layer for the whole project, and from Week 2 onward it
is how results are managed. `preprocessing/outputs/` stays as the working copy
that the pipeline scripts write into; `outputs/` is the curated, plainly-named
version a human opens to see what was done.

Three rules for every figure in here:

1. **It carries its own reference.** Every figure shows the "before" next to the
   "after", inside the same image. A picture of a result you cannot compare
   against anything is not evidence of anything.
2. **It is named in plain words.** `skull-stripped-vs-original.png`, not
   `stage3_fig2.png`. The folder and file names should tell the story without
   opening anything.
3. **It is generated by this script**, never a screenshot, with the git commit
   stamped into the title (CLAUDE.md Section 5.7).

The same three subjects — the median lesion-burden subject at each site — appear
in every figure, so the gallery reads as one continuous story rather than a pile
of unrelated pictures.

    code/.venv/bin/python -m preprocessing.make_outputs
"""

