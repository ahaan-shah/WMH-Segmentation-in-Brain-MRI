def figure_overview(subjects, commit, logger) -> None:
    columns = [
        "1. ORIGINAL SCAN\n(what we downloaded)",
        "2. head found\n(air removed)",
        "3. scanner brightness\ngradient measured",
        "4. gradient removed",
        "5. SKULL REMOVED\n(brain only)",
        "6. BRIGHTNESS NORMALISED\n+ true lesions in green",
    ]
    fig, axes = plt.subplots(len(subjects), 6, figsize=(19, 3.7 * len(subjects)))
    axes = np.atleast_2d(axes)

    for row, s in enumerate(subjects):
        _panel(axes[row, 0], s.slice_of(s.raw), "", vmax=s.raw_vmax)
        _panel(axes[row, 1], s.slice_of(s.raw), "", vmax=s.raw_vmax)
        axes[row, 1].contour(s.slice_of(s.head).T[::-1], colors="deepskyblue", linewidths=0.9)

        field = np.where(s.head, s.bias, np.nan)
        _panel(axes[row, 2], s.slice_of(field), "", vmin=0.85, vmax=1.15, cmap="RdBu_r")

        _panel(axes[row, 3], s.slice_of(s.n4), "", vmax=s.raw_vmax)

        stripped = np.where(s.brain, s.n4, 0.0)
        _panel(axes[row, 4], s.slice_of(stripped), "", vmax=s.brain_vmax)

        _panel(axes[row, 5], s.slice_of(s.norm), "", vmin=0, vmax=2.0)
        axes[row, 5].contour(s.slice_of(s.lesion).T[::-1], colors=LESION_GREEN, linewidths=0.8)

        axes[row, 0].axis("on")
        axes[row, 0].set_xticks([]); axes[row, 0].set_yticks([])
        axes[row, 0].set_ylabel(s.label, fontsize=11, fontweight="bold")
        for spine in axes[row, 0].spines.values():
            spine.set_edgecolor("#B22222"); spine.set_linewidth(2)

    for column, label in enumerate(columns):
        axes[0, column].set_title(label, fontsize=10, pad=10,
                                  fontweight="bold" if column in (0, 4, 5) else "normal",
                                  color="#B22222" if column == 0 else "black")

    _stamp(fig, "WEEK 2 — everything we did to the scans, left to right",
           "Column 1 (red border) is the untouched original. One patient per hospital; "
           "each row is the same brain all the way across.", commit)
    fig.tight_layout(rect=(0, 0, 1, 0.94))
    _save(fig, WEEK2 / "00-overview" / "full-pipeline-all-sites.png", commit, logger)


