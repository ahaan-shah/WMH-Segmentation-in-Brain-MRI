VENTRICLE_C = "#00BFFF"   # blue   — the structure we measure from
PERIVENT_C = "#FFD700"    # gold   — within 10 mm
DEEP_C = "#FF3B30"        # red    — beyond 10 mm
TRUTH_C = "#39FF14"       # green  — the expert reference


def _stamp(fig, title, subtitle, commit):
    """Title and caption, positioned in INCHES from the top.

    Figure coordinates are fractions of the figure, so a fixed y collides on a
    tall figure and floats away on a short one. Earlier this produced a title
    printed straight through its own caption on the three-row panels. Offsets
    are therefore converted from inches, and the caption is placed by its TOP
    edge so extra wrapped lines grow downward into the margin rather than
    upward into the title.
    """
    height = fig.get_size_inches()[1]
    fig.suptitle(title, fontsize=14, fontweight="bold", y=1.0 - 0.22 / height)
    fig.text(0.5, 1.0 - 0.52 / height, subtitle, ha="center", va="top",
             fontsize=9.5, style="italic", wrap=True)
    fig.text(0.995, 0.004, f"commit {commit[:8]}", ha="right", fontsize=6.5, color="grey")


def _reserve(fig, inches=1.15):
    """Leave `inches` of clear space at the top for the title block."""
    height = fig.get_size_inches()[1]
    fig.tight_layout(rect=[0, 0, 1, 1.0 - inches / height])


def _save(fig, path, commit, logger):
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=130, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    write_manifest(path, generating_script=f"code/features/{SCRIPT_NAME}.py",
                   extra={"commit": commit})
    logger.info("  %s", path.relative_to(PROJECT_ROOT))


def _panel(axis, image, title, *, cmap="gray"):
    axis.imshow(np.rot90(image), cmap=cmap)
    axis.set_title(title, fontsize=9)
    axis.axis("off")


def _overlay(axis, mask, colour, alpha=0.85):
    rgba = np.zeros((*mask.shape, 4))
    rgba[mask] = [*matplotlib.colors.to_rgb(colour), alpha]
    axis.imshow(np.rot90(rgba))


def _busiest_slice(mask: np.ndarray) -> int:
    """The slice with the most lesion voxels — see rule 2 in the docstring."""
    per_slice = mask.reshape(-1, mask.shape[2]).sum(axis=0)
    return int(np.argmax(per_slice))


def _one_per_site(keys, subjects):
    chosen, seen = {}, set()
    for key in keys:
        site = subjects[key].site
        if site not in seen and derived_exists(key, VENTRICLES):
            seen.add(site)
            chosen[site] = key
    return chosen


