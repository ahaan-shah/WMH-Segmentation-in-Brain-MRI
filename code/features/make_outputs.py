"""Week 4 gallery — the labelling and measurement figures (R5-R9).

Same three rules the Week 2 and Week 3 galleries follow:

1. **Every figure carries its own reference inside the image.** A ventricle
   outline on its own proves nothing; the un-annotated image has to sit beside
   it so a reader can judge the outline rather than take it on trust.
2. **Pick the slice with the most lesion, never the middle slice.** Week 1
   learned this the hard way: Amsterdam's FLAIR is 3D-acquired with a much
   larger superior-inferior field of view, so `shape[2]//2` lands on an orbital
   slice there while being mid-brain everywhere else.
3. **Generated by this script**, never a screenshot, with the commit stamped on.

    code/.venv/bin/python -m features.make_outputs
"""

